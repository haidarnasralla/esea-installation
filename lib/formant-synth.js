const CHIRP_SIZE = 41;
const FS = 8000; // Sample rate

class LPCSynth {
  constructor() {
    this.ctx = null;
    this.masterGain = null;
    this.initialized = false;
  }

  init() {
    if (this.initialized) return;
    this.ctx = new (window.AudioContext || window.webkitAudioContext)();
    this.masterGain = this.ctx.createGain();
    this.masterGain.gain.value = 0.5;
    this.masterGain.connect(this.ctx.destination);
    this.initialized = true;
    console.log('LPCSynth initialized (TMS5100 compatible)');
  }

  async resume() {
    if (this.ctx && this.ctx.state === 'suspended') {
      await this.ctx.resume();
    }
  }

  /**
   * Reverse bits in a byte - TMS5100 ROM data is bit-reversed
   */
  rev(a) {
    a = ((a >> 4) | (a << 4)) & 0xFF;
    a = (((a & 0xCC) >> 2) | ((a & 0x33) << 2)) & 0xFF;
    a = (((a & 0xAA) >> 1) | ((a & 0x55) << 1)) & 0xFF;
    return a;
  }

  /**
   * Decode and synthesize LPC data - direct port of Talkie's ISR
   */
  decodeLPC(data) {
    const samples = [];
    
    // Bit reading state
    let ptrAddr = 0;
    let ptrBit = 0;

    const getBits = (bits) => {
      let value;
      let d = this.rev(data[ptrAddr]) << 8;
      if (ptrBit + bits > 8 && ptrAddr + 1 < data.length) {
        d |= this.rev(data[ptrAddr + 1]);
      }
      d <<= ptrBit;
      value = (d >> (16 - bits)) & ((1 << bits) - 1);
      ptrBit += bits;
      if (ptrBit >= 8) {
        ptrBit -= 8;
        ptrAddr++;
      }
      return value;
    };

    // Synthesis state - matches Talkie's global variables
    let synthPeriod = 0;
    let synthEnergy = 0;
    let synthK1 = 0, synthK2 = 0;
    let synthK3 = 0, synthK4 = 0, synthK5 = 0, synthK6 = 0, synthK7 = 0, synthK8 = 0, synthK9 = 0, synthK10 = 0;

    // Filter state
    let x0 = 0, x1 = 0, x2 = 0, x3 = 0, x4 = 0, x5 = 0, x6 = 0, x7 = 0, x8 = 0, x9 = 0;
    
    // Excitation state
    let periodCounter = 0;
    let synthRand = 1;

    // Process frames
    let frameCount = 0;
    while (ptrAddr < data.length && frameCount < 500) {
      frameCount++;
      
      // Read frame header
      const energy = getBits(4);
      
      if (energy === 0) {
        // Energy = 0: rest frame
        synthEnergy = 0;
      } else if (energy === 0xF) {
        // Energy = 15: stop frame
        synthEnergy = 0;
        synthK1 = synthK2 = synthK3 = synthK4 = synthK5 = 0;
        synthK6 = synthK7 = synthK8 = synthK9 = synthK10 = 0;
        break;
      } else {
        synthEnergy = tmsEnergy[energy];
        const repeat = getBits(1);
        synthPeriod = tmsPeriod[getBits(6)];
        
        if (!repeat) {
          // All frames use first 4 coefficients
          synthK1 = toSigned16(tmsK1[getBits(5)]);
          synthK2 = toSigned16(tmsK2[getBits(5)]);
          synthK3 = toSigned8(tmsK3[getBits(4)]);
          synthK4 = toSigned8(tmsK4[getBits(4)]);
          
          if (synthPeriod) {
            // Voiced frames use 6 extra coefficients
            synthK5 = toSigned8(tmsK5[getBits(4)]);
            synthK6 = toSigned8(tmsK6[getBits(4)]);
            synthK7 = toSigned8(tmsK7[getBits(4)]);
            synthK8 = toSigned8(tmsK8[getBits(3)]);
            synthK9 = toSigned8(tmsK9[getBits(3)]);
            synthK10 = toSigned8(tmsK10[getBits(3)]);
          }
        }
      }

      // Render samples for this frame (25ms = 200 samples at 8kHz)
      for (let i = 0; i < 200; i++) {
        let u0, u1, u2, u3, u4, u5, u6, u7, u8, u9, u10;

        // Generate excitation
        if (synthPeriod) {
          // Voiced source
          if (periodCounter < synthPeriod) {
            periodCounter++;
          } else {
            periodCounter = 0;
          }
          if (periodCounter < CHIRP_SIZE) {
            u10 = (chirp[periodCounter] * synthEnergy) >> 8;
          } else {
            u10 = 0;
          }
        } else {
          // Unvoiced source (noise)
          synthRand = (synthRand >> 1) ^ ((synthRand & 1) ? 0xB800 : 0);
          u10 = (synthRand & 1) ? synthEnergy : -synthEnergy;
        }

        // Lattice filter forward path
        u9 = u10 - ((synthK10 * x9) >> 7);
        u8 = u9 - ((synthK9 * x8) >> 7);
        u7 = u8 - ((synthK8 * x7) >> 7);
        u6 = u7 - ((synthK7 * x6) >> 7);
        u5 = u6 - ((synthK6 * x5) >> 7);
        u4 = u5 - ((synthK5 * x4) >> 7);
        u3 = u4 - ((synthK4 * x3) >> 7);
        u2 = u3 - ((synthK3 * x2) >> 7);
        u1 = u2 - ((synthK2 * x1) >> 15);
        u0 = u1 - ((synthK1 * x0) >> 15);

        // Output clamp
        if (u0 > 511) u0 = 511;
        if (u0 < -512) u0 = -512;

        // Lattice filter reverse path
        x9 = x8 + ((synthK9 * u8) >> 7);
        x8 = x7 + ((synthK8 * u7) >> 7);
        x7 = x6 + ((synthK7 * u6) >> 7);
        x6 = x5 + ((synthK6 * u5) >> 7);
        x5 = x4 + ((synthK5 * u4) >> 7);
        x4 = x3 + ((synthK4 * u3) >> 7);
        x3 = x2 + ((synthK3 * u2) >> 7);
        x2 = x1 + ((synthK2 * u1) >> 15);
        x1 = x0 + ((synthK1 * u0) >> 15);
        x0 = u0;

        // Convert to float (-1 to 1)
        samples.push(u0 / 512);
      }
    }

    console.log(`Decoded ${frameCount} frames, ${samples.length} samples`);
    return samples;
  }

  /**
   * Play LPC encoded word data
   */
  playWord(data) {
    const samples = this.decodeLPC(data);
    if (samples.length === 0) return 0;

    // Create buffer at native sample rate
    const nativeSamples = Math.ceil(samples.length * this.ctx.sampleRate / FS);
    const buffer = this.ctx.createBuffer(1, nativeSamples, this.ctx.sampleRate);
    const output = buffer.getChannelData(0);
    
    // Upsample with sample-and-hold for authentic sound
    const ratio = FS / this.ctx.sampleRate;
    for (let i = 0; i < nativeSamples; i++) {
      const srcIdx = Math.floor(i * ratio);
      output[i] = samples[Math.min(srcIdx, samples.length - 1)];
    }

    const source = this.ctx.createBufferSource();
    source.buffer = buffer;
    source.connect(this.masterGain);
    source.start();
    
    return buffer.duration;
  }

  /**
   * Speak text - finds words in vocabulary or plays random words
   */
  speak(text) {
    if (!this.initialized) this.init();
    this.resume();

    const words = text.toLowerCase().split(/\s+/);
    let delay = 0;

    for (const word of words) {
      if (VOCAB[word]) {
        setTimeout(() => this.playWord(VOCAB[word]), delay * 1000);
        delay += 0.5;
      } else {
        // Word not in vocab - play random vocab words
        const syllables = Math.max(1, Math.ceil(word.length / 3));
        const vocabKeys = Object.keys(VOCAB).filter(k => k !== 'pause');
        for (let i = 0; i < syllables; i++) {
          const randomWord = vocabKeys[Math.floor(Math.random() * vocabKeys.length)];
          setTimeout(() => this.playWord(VOCAB[randomWord]), delay * 1000);
          delay += 0.35;
        }
      }
    }
  }

  setVolume(value) {
    if (this.masterGain) {
      this.masterGain.gain.value = Math.max(0, Math.min(1, value));
    }
  }
}

const lpcSynth = new LPCSynth();
export default lpcSynth;
export { LPCSynth, VOCAB };
